class FakeGitSync:
    """Recording GitSync for commit-per-edit and push-flow tests."""

    def __init__(self, reject_pushes: int = 0, conflict_files: list[str] | None = None) -> None:
        self.commits: list[str] = []
        #: The author of each commit, in step with `commits`.
        self.authors: list[Actor] = []
        self.pulls = 0
        self.pushes = 0
        self._reject_pushes = reject_pushes
        self._conflict_files = conflict_files

    def commit_all(self, *, message: str, author: Actor) -> None:
        self.commits.append(message)
        self.authors.append(author)

    def pull(self) -> None:
        self.pulls += 1
        if self._conflict_files is not None:
            raise SyncConflictError(self._conflict_files)

    def push(self) -> None:
        if self._reject_pushes > 0:
            self._reject_pushes -= 1
            raise SyncRejectedError("upstream moved")
        self.pushes += 1

    def status(self) -> SyncStatus:
        return SyncStatus(unpushed_commits=len(self.commits), diff_stat="stub diff")


class StubValidator:
    """Deterministic PlaybookValidator for gated-edit tests."""

    def __init__(self, ok: bool) -> None:
        self._ok = ok
        self.calls = 0

    def validate(self) -> ValidationReport:
        self.calls += 1
        return ValidationReport(
            tests_passed=self._ok,
            links_ok=self._ok,
            tests_output="stub tests",
            links_output="stub links",
        )


