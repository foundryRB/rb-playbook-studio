# The stand-in for the playbook's own installer. Its agent renderings are
# deliberately unlike anything the studio could produce on its own: a served
# agent carrying this marker proves the studio called the installer rather than
# spelling the runtime's fields itself (playbook INT-TOOL-002). Run from an
# unpacked install bundle (its manifest.json beside scripts/), it copies the
# bundle's files and says so in one line, which is how a test sees the bundle's
# own installer run with the flags the install line passed it.
_INSTALL_PLAYBOOK = """
import argparse, json, os, shutil
from pathlib import Path


class _SkillHome:
    def __init__(self, install_hint, dest):
        self.install_hint = install_hint
        self.dest = dest


_SHARED_SKILLS = _SkillHome("~/.claude/skills/", "runtime_dir")
_CODEX_SKILLS = _SkillHome("~/.agents/skills/", "codex_skills_dir")


class _Runtime:
    def __init__(self, name, install_hint, tag, dest, suffix=".md", skills=_SHARED_SKILLS):
        self.name = name
        self.install_hint = install_hint
        self._tag = tag
        self.dest = dest
        self.suffix = suffix
        self.skills = skills

    def render(self, raw):
        return "---\\nrendered-by-installer: " + self._tag + "\\n---\\n\\n" + raw


AGENT_RUNTIMES = (
    _Runtime("claude-code", "~/.claude/agents/", "claude-shape", "agents_dir"),
    _Runtime("opencode", "~/.config/opencode/agents/", "opencode-shape", "opencode_agents_dir"),
    _Runtime(
        "codex", "~/.codex/agents/", "codex-shape", "codex_agents_dir", ".toml", _CODEX_SKILLS
    ),
)

if __name__ == "__main__":
    home = Path.home()
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", action="append", default=None)
    ap.add_argument("--runtime-dir", type=Path, default=home / ".claude" / "skills")
    ap.add_argument("--codex-skills-dir", type=Path, default=home / ".agents" / "skills")
    ap.add_argument("--codex-agents-dir", type=Path, default=home / ".codex" / "agents")
    ap.add_argument("--agents-dir", type=Path, default=home / ".claude" / "agents")
    config = Path(os.environ.get("XDG_CONFIG_HOME") or home / ".config")
    ap.add_argument("--opencode-agents-dir", type=Path, default=config / "opencode" / "agents")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--prune", action="store_true")
    a = ap.parse_args()
    root = Path(__file__).resolve().parents[1]
    if (root / "manifest.json").is_file():
        manifest = json.loads((root / "manifest.json").read_text(encoding="utf-8"))
        runtime = {r.name: r for r in AGENT_RUNTIMES}[manifest["runtime"]]
        for entry in manifest["files"]:
            kind, *rest = entry["path"].split("/")
            base = getattr(a, runtime.skills.dest if kind == "skills" else runtime.dest)
            target = base.joinpath(*rest)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(root / entry["path"], target)
        print(
            "stand-in installer: %d file(s) from the bundle for %s%s"
            % (len(manifest["files"]), manifest["runtime"], " with --prune" if a.prune else "")
        )
    else:
        source = root / "skills"
        names = a.only or [d.name for d in source.iterdir() if (d / "SKILL.md").is_file()]
        a.runtime_dir.mkdir(parents=True, exist_ok=True)
        for n in names:
            t = a.runtime_dir / n
            if t.exists():
                shutil.rmtree(t)
            shutil.copytree(source / n, t, ignore=shutil.ignore_patterns("__pycache__"))
"""


